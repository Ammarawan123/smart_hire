def pdf(path: Path, title: str, sections):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    from xml.sax.saxutils import escape
    st = getSampleStyleSheet(); doc = SimpleDocTemplate(str(path), pagesize=A4, title=title, leftMargin=48, rightMargin=48, topMargin=48, bottomMargin=48)
    fl = [Paragraph(escape(title), st["Title"]), Paragraph("Generated by scripts/build_docs.py from the repository state; see research/references.json for verification status.", st["Italic"]), Spacer(1, 10)]
    for h, body in sections:
        fl.append(Paragraph(escape(h), st["Heading2"]))
        for para in body:
            fl.append(Paragraph(escape(para), st["BodyText"]))
        fl.append(Spacer(1, 6))
    doc.build(fl)

