def bib(r):
    kind = "inproceedings" if r["type"] == "conference" else ("article" if r["type"] == "journal" else "misc")
    f = [f'  title = {{{r["title"]}}}', f'  year = {{{r["year"]}}}']
    if r.get("authors"): f.insert(0, f'  author = {{{r["authors"]}}}')
    for k, b in (("venue", "booktitle" if kind == "inproceedings" else "journal"), ("doi", "doi"), ("arxiv", "eprint"), ("url", "url"), ("pages", "pages")):
        if r.get(k): f.append(f'  {b} = {{{r[k]}}}')
    f.append(f'  note = {{status: {r["status"]}; {r.get("note","")}}}')
    return f"@{kind}{{{r['key']},\n" + ",\n".join(f) + "\n}\n"

def docstrings(d: Path):
    out = []
    for p in sorted(d.glob("*.py")):
        try:
            t = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
            doc = (ast.get_docstring(t) or "").strip().splitlines()
            out.append((p.name, (doc[0] if doc else "(no module docstring)")[:170]))
        except SyntaxError:
            out.append((p.name, "(could not parse)"))
    return out

